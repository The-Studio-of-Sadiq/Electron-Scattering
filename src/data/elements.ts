// Helper to construct fallback default for any Z (1 to 103)
export function getElementByZ(z: number): ElementData {
  if (ELEMENTS_DATABASE[z]) {
    return ELEMENTS_DATABASE[z];
  }

  // General empirical estimate for any element Z
  const atomicMass = Math.round(z * 2.2 + (z > 20 ? (z - 20) * 0.3 : 0));
  const polarizability = Math.max(1.0, 50.0 / Math.pow(z, 0.4));
  const cutoffRadius = 1.0 + 0.01 * z;

  return {
    z,
    symbol: `Z=${z}`,
    name: `Element Z=${z}`,
    atomicMass,
    polarizability,
    cutoffRadius,
    electronConfig: `Z=${z}`,
    group: z > 89 ? 'Actinide' : z > 57 ? 'Lanthanide' : 'Heavy Element',
    diracFockA: [0.15, 0.65, 0.2],
    diracFockAlpha: [1.0 + 0.1 * z, 0.5 + 0.04 * z, 0.2 + 0.02 * z],
  };
}
